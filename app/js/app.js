// ---------- Animations ----------
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

// Bandeau défilant : catégories et soins phares, répétés pour une boucle continue.
function renderMarquee() {
  const L = state.lang;
  const words = [
    ...state.catalog.categories.map((c) => `${c.icon} ${tr(c.name, L)}`),
    ...activeServices().filter((s) => s.featured).map((s) => tr(s.name, L))
  ];
  const line = words.map((w) => `<span>${esc(w)}</span><i>✦</i>`).join("");
  $("#marquee").innerHTML = line + line;
}

function updateCounts() {
  const stats = state.catalog.settings.stats ?? window.PALM_DEFAULT.settings.stats;
  $("#countYears").dataset.count = stats.years;
  $("#countBrands").dataset.count = stats.brands;
  $("#countServices").dataset.count = activeServices().length;
  $("#countPacks").dataset.count = activeServices().filter((s) => s.cat === "packs").length;
  if ($(".why").classList.contains("counted")) $$(".why [data-count]").forEach((b) => (b.textContent = b.dataset.count));
}

// Chiffres qui défilent de 0 à leur valeur quand la section apparaît.
function countUp(section) {
  section.classList.add("counted");
  $$("[data-count]", section).forEach((b) => {
    const target = Number(b.dataset.count) || 0;
    if (reduceMotion) return (b.textContent = target);
    const start = performance.now();
    const step = (now) => {
      const p = Math.min(1, (now - start) / 1400);
      b.textContent = Math.round(target * (1 - Math.pow(1 - p, 3)));
      if (p < 1) requestAnimationFrame(step);
    };
    requestAnimationFrame(step);
  });
}

// Apparition douce des sections au défilement.
function setupReveal() {
  const sections = $$("#packs .section, .why, #mariee, #services, #contact");
  if (reduceMotion || !("IntersectionObserver" in window)) {
    sections.forEach((el) => el.classList.add("revealed"));
    return countUp($(".why"));
  }
  const io = new IntersectionObserver((entries) => entries.forEach((e) => {
    if (!e.isIntersecting) return;
    e.target.classList.add("revealed");
    if (e.target.classList.contains("why")) countUp(e.target);
    io.unobserve(e.target);
  }), { threshold: 0.12 });
  sections.forEach((el) => {
    el.classList.add("reveal");
    io.observe(el);
  });
}

function bump(el) {
  if (!el || reduceMotion) return;
  el.classList.remove("bump");
  void el.offsetWidth; // relance l'animation
  el.classList.add("bump");
}

