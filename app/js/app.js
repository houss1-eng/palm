const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];
// Textes : d'abord ceux modifiés dans l'admin (onglet Site), sinon ceux de l'app.
const t = (key) => {
  const custom = state.catalog.settings.texts?.[key] ?? window.PALM_DEFAULT.settings.texts[key];
  return (custom && tr(custom, state.lang)) || (I18N[state.lang][key] ?? I18N.fr[key] ?? key);
};
const errText = (err) => tr(Api.friendlyError(err), state.lang);

const activeServices = () => state.catalog.services.filter((s) => s.active !== false);
const findService = (id) => state.catalog.services.find((s) => s.id === id);

function priceHtml(s) {
  if (s.price == null) return `<span class="price on-request">${esc(t("onRequest"))}</span>`;
  const old = s.oldPrice ? `<s class="old">${s.oldPrice} DT</s>` : "";
  return `<span class="price">${old}<b>${s.price}</b> DT</span>`;
}

function addBtn(s) {
  const on = state.cart.has(s.id);
  return `<button class="add-btn${on ? " on" : ""}" data-add="${esc(s.id)}" aria-pressed="${on}">
    ${on ? "✓ " + esc(t("added")) : "+ " + esc(t("add"))}
  </button>`;
}

function card(s) {
  const L = state.lang;
  const badge = s.badge ? `<span class="badge">${esc(tr(s.badge, L))}</span>` : "";
  const dur = s.duration ? `<span class="dur">⏱ ${s.duration} ${esc(t("min"))}</span>` : "";
  const items = s.items && s.items.length
    ? `<details class="items"><summary>${esc(t("includes"))} (${s.items.length})</summary>
         <ol>${s.items.map((i) => `<li>${esc(tr(i, L))}</li>`).join("")}</ol>
       </details>`
    : "";
  // Photo entière (jamais coupée), cliquable pour l'agrandir ; sinon un visuel
  // aux couleurs du centre avec l'icône de la catégorie.
  const icon = state.catalog.categories.find((c) => c.id === s.cat)?.icon || "🌴";
  const name = tr(s.name, L);
  const media = s.image
    ? `<button type="button" class="card-img" data-zoom="${esc(s.image)}" data-cap="${esc(name)}"
         style="--photo:url('${esc(new URL(s.image, location.href).href)}')" aria-label="${esc(t("zoom"))} : ${esc(name)}">
         <img src="${esc(s.image)}" alt="${esc(name)}" loading="lazy">
         <span class="zoom-ico" aria-hidden="true">⤢</span>
       </button>`
    : `<div class="card-img ph" aria-hidden="true"><span>${esc(icon)}</span></div>`;
  return `<article class="card">
    ${media}
    <div class="card-head">
      <h3>${esc(tr(s.name, L))}</h3>${badge}
    </div>
    ${s.desc ? `<p class="desc">${esc(tr(s.desc, L))}</p>` : ""}
    ${items}
    <div class="card-foot">
      <div class="meta">${priceHtml(s)}${dur}</div>
      ${addBtn(s)}
    </div>
  </article>`;
}

function row(s) {
  return `<div class="row">
    <span class="row-name">${esc(tr(s.name, state.lang))}</span>
    <span class="row-dots"></span>
    ${priceHtml(s)}
    ${addBtn(s)}
  </div>`;
}

// Services avec photo ou description en cartes ; les autres en liste de prix.
// Laser : séances à l'unité d'abord, puis les offres mariée.
function renderList(list, laserTitles = false) {
  const isCard = (s) => s.desc || s.image;
  const rows = list.filter((s) => !isCard(s));
  const cards = list.filter(isCard);
  const grid = (items) => `<div class="grid">${items.map(card).join("")}</div>`;
  let html = rows.length ? `<div class="price-list">${rows.map(row).join("")}</div>` : "";
  if (laserTitles) {
    const sessions = cards.filter((s) => !s.desc);
    const offers = cards.filter((s) => s.desc);
    if (sessions.length) html += `<h4 class="list-title">${esc(t("perSession"))}</h4>${grid(sessions)}`;
    if (offers.length) html += `<h4 class="list-title">${esc(t("bridalOffers"))}</h4>${grid(offers)}`;
  } else if (cards.length) {
    html += grid(cards);
  }
  return html;
}

function renderStatic() {
  document.documentElement.lang = state.lang;
  document.documentElement.dir = state.lang === "ar" ? "rtl" : "ltr";
  $$("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  $$("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  $("#langBtn").textContent = state.lang === "fr" ? "عربي" : "FR";
  $("#cityLabel").textContent = tr(state.catalog.settings.city, state.lang);
  const hero = state.catalog.settings.heroImage;
  $(".hero-bg").style.backgroundImage = hero ? `url("${new URL(hero, location.href).href}")` : "";
}

function renderFeatured() {
  $("#featured").innerHTML = activeServices().filter((s) => s.featured).map(card).join("");
}

function renderBridal() {
  const L = state.lang;
  const groups = state.catalog.categories
    .map((c) => ({ c, list: activeServices().filter((s) => s.bridal && s.cat === c.id) }))
    .filter((g) => g.list.length);
  $("#bridal").innerHTML = groups.map(({ c, list }) => `
    <div class="bride-group">
      <h4>${c.icon} ${esc(tr(c.name, L))}</h4>
      <ul>${list.map((s) => `<li>
        ${s.image ? `<button type="button" class="thumb" data-zoom="${esc(s.image)}" data-cap="${esc(tr(s.name, L))}" aria-label="${esc(t("zoom"))}"><img src="${esc(s.image)}" alt="" loading="lazy"></button>` : ""}
        <span>${esc(tr(s.name, L))}</span>
        <div class="bride-end">${priceHtml(s)}${addBtn(s)}</div>
      </li>`).join("")}</ul>
    </div>`).join("");
}

function renderCatalog() {
  const L = state.lang;
  // La catégorie affichée a pu être supprimée par l'admin.
  if (!state.catalog.categories.some((c) => c.id === state.cat)) state.cat = state.catalog.categories[0]?.id;
  $("#chips").innerHTML = state.catalog.categories.map((c) => `
    <button class="chip${!state.query && c.id === state.cat ? " on" : ""}" data-cat="${esc(c.id)}">
      <span aria-hidden="true">${c.icon}</span> ${esc(tr(c.name, L))}
    </button>`).join("");

  const q = state.query.trim().toLowerCase();
  let html;
  if (q) {
    const hits = activeServices().filter((s) =>
      [s.name.fr, s.name.ar, s.desc?.fr, s.desc?.ar].some((v) => v && v.toLowerCase().includes(q))
    );
    html = hits.length ? renderList(hits) : `<p class="empty">${esc(t("noResults"))}</p>`;
  } else {
    html = renderList(activeServices().filter((s) => s.cat === state.cat), state.cat === "laser");
  }
  $("#catalog").innerHTML = html;
}

function renderCart() {
  const L = state.lang;
  const items = [...state.cart].map(findService).filter(Boolean);
  for (const id of ["#cartCount", "#navCount"]) {
    $(id).textContent = items.length;
    $(id).hidden = items.length === 0;
  }

  $("#cartList").innerHTML = items.length
    ? items.map((s) => `<li>
        <span>${esc(tr(s.name, L))}</span>
        ${priceHtml(s)}
        <button class="x" data-remove="${esc(s.id)}" aria-label="${esc(t("remove"))}">✕</button>
      </li>`).join("")
    : `<li class="empty">${esc(t("emptyCart"))}</li>`;

  const total = items.reduce((sum, s) => sum + (s.price || 0), 0);
  const unknown = items.some((s) => s.price == null);
  $("#cartTotal").innerHTML = items.length
    ? `<span>${esc(t("total"))}</span><b>${total} DT</b>${unknown ? `<small>${esc(t("plusOnRequest"))}</small>` : ""}`
    : "";

  $("#needLogin").hidden = !!state.user;
  $("#bookForm").hidden = !state.user;
}

