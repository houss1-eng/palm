document.addEventListener("click", async (e) => {
  const zoom = e.target.closest("[data-zoom]");
  if (zoom) return openLightbox(zoom.dataset.zoom, zoom.dataset.cap);
  const add = e.target.closest("[data-add]");
  if (add) {
    const id = add.dataset.add;
    const added = !state.cart.has(id);
    added ? state.cart.add(id) : state.cart.delete(id);
    renderFeatured();
    renderBridal();
    renderCatalog();
    renderCart();
    if (added) bump($(".topbar [data-book]"));
    return;
  }
  const rm = e.target.closest("[data-remove]");
  if (rm) {
    state.cart.delete(rm.dataset.remove);
    renderAll();
    return;
  }
  const chip = e.target.closest("[data-cat]");
  if (chip) {
    state.cat = chip.dataset.cat;
    state.query = "";
    $("#search").value = "";
    renderCatalog();
    return;
  }
  if (e.target.closest("[data-book]")) return openSheet();
  if (e.target.closest("[data-account]")) return openAccount();
  if (e.target.closest("[data-close]")) return e.target.closest("dialog").close();

  const mode = e.target.closest("[data-mode]");
  if (mode) {
    state.authMode = mode.dataset.mode;
    renderAccount();
    return;
  }
  const cancel = e.target.closest("[data-cancel]");
  if (cancel) {
    if (!confirm(t("cancelConfirm"))) return;
    try {
      await Api.setStatus(cancel.dataset.cancel, "annulé");
      state.bookings = await Api.myBookings();
      renderAccount();
      toast(t("cancelled"));
    } catch (err) {
      toast(errText(err));
    }
    return;
  }
  if (e.target.closest("#pushBtn")) {
    try {
      await Api.enablePush();
      toast(t("notifReady"));
    } catch (err) {
      toast(err.message === "permission" ? t("notifDenied") : t("notifError"));
    }
    renderAccount();
    return;
  }
  if (e.target.closest("#logoutBtn")) {
    await Api.signOut();
    await refreshUser(null);
  }
});

